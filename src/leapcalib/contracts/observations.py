"""Observations: metric samples that carry their own clock, provenance and quality.

Two confusions are expensive enough here to be made structurally impossible.

**Preview is not evidence.** A LeapFlow preview is a bounded JPEG for a human or
an LLM, and a colourised depth image is a picture *of* depth. Both look like
camera data and neither has the metric content a solve needs: the JPEG has been
resampled and compressed, the colourisation has been quantised through a palette.
Feeding either into a residual produces numbers with no stated relationship to
millimetres. So provenance is a required field, and only metric RGB-D (or a
replay of it) is admissible -- :data:`CALIBRATION_PROVENANCE` is enforced in
:class:`RgbdObservation` rather than documented as a convention.

**A timestamp is not an exposure instant.** ``Frameset`` is "stamped when it
reached this process", and the capture group's 50 ms default tolerance is a
preview-grade freshness bound, not a synchronisation guarantee. A stamp therefore
names its *domain* (whose clock) and its *semantics* (what the number means), and
differencing two stamps from unrelated clocks raises instead of returning a
plausible-looking delta. A host monotonic and a node monotonic have unrelated
origins; subtracting them yields the age of nothing.
"""

from __future__ import annotations

import math
from dataclasses import dataclass, field
from typing import Any, Iterator, Mapping, Protocol, Sequence, runtime_checkable

from leapcalib.contracts.failures import (
    FAILURE_CLOCK_DOMAIN_MISMATCH,
    FAILURE_PROVENANCE_REFUSED,
    CalibrationFailure,
)
from leapcalib.contracts.identity import ModelIdentity, StreamProfile, digest_of
from leapcalib.contracts.units import canonical_number

CLOCK_NODE_MONOTONIC = "node_monotonic"
"""``time.monotonic()`` inside the hardware node process. Comparable only with itself."""
CLOCK_HOST_MONOTONIC = "host_monotonic"
"""``time.monotonic()`` on the Mac host. Unrelated origin to the node's."""
CLOCK_WALL = "wall"
"""``time.time()``; comparable across machines only to NTP accuracy, and may step."""
CLOCK_DEVICE = "device"
"""The camera's own clock, as the SDK reports it. Unrelated to any host clock."""
CLOCK_DOMAINS = frozenset({CLOCK_NODE_MONOTONIC, CLOCK_HOST_MONOTONIC, CLOCK_WALL, CLOCK_DEVICE})

STAMP_RECEIPT = "process_receipt"
"""When the sample reached the consuming process -- what LeapFlow frames carry today."""
STAMP_EXPOSURE_MIDPOINT = "exposure_midpoint"
"""When the sensor actually integrated the sample. Not established for these cameras."""
STAMP_SETTLED_CAPTURE = "settled_capture"
"""Captured after measured stillness, so receipt-versus-exposure no longer matters."""
STAMP_SEMANTICS = frozenset({STAMP_RECEIPT, STAMP_EXPOSURE_MIDPOINT, STAMP_SETTLED_CAPTURE})

PROVENANCE_METRIC_RGBD = "metric_rgbd"
"""Raw aligned colour plus 16-bit depth with live intrinsics and a depth scale."""
PROVENANCE_REPLAY = "replay"
"""A stored metric observation read back from an evidence bundle."""
PROVENANCE_PREVIEW_JPEG = "preview_jpeg"
"""A bounded JPEG for a human or a model. Never calibration evidence."""
PROVENANCE_COLORIZED_DEPTH = "colorized_depth"
"""Depth rendered through a palette for viewing. Never calibration evidence."""
PROVENANCE_SYNTHETIC = "synthetic"
"""Generated by a test or an injection study. Admissible, and marked so it cannot pose as measured."""
PROVENANCES = frozenset(
    {
        PROVENANCE_METRIC_RGBD,
        PROVENANCE_REPLAY,
        PROVENANCE_PREVIEW_JPEG,
        PROVENANCE_COLORIZED_DEPTH,
        PROVENANCE_SYNTHETIC,
    }
)

CALIBRATION_PROVENANCE = frozenset(
    {PROVENANCE_METRIC_RGBD, PROVENANCE_REPLAY, PROVENANCE_SYNTHETIC}
)
"""The provenances a geometric residual may consume."""

MAX_SAMPLES = 20000
"""Per-observation sample bound, so one record cannot exhaust a small board's memory."""


@dataclass(frozen=True)
class Stamp:
    """When a sample happened: a number, whose clock it is on, and what it means.

    ``uncertainty_s`` is the honest width of the instant, not a formality. For a
    receipt stamp it should cover transport and decode latency; a zero there is a
    claim that the sample was observed exactly when it was received.
    """

    seconds: float
    domain: str = CLOCK_NODE_MONOTONIC
    semantics: str = STAMP_RECEIPT
    uncertainty_s: float = 0.0

    def __post_init__(self) -> None:
        object.__setattr__(self, "seconds", canonical_number(self.seconds))
        object.__setattr__(self, "uncertainty_s", canonical_number(self.uncertainty_s))
        if self.domain not in CLOCK_DOMAINS:
            raise ValueError(f"clock domain must be one of {sorted(CLOCK_DOMAINS)}")
        if self.semantics not in STAMP_SEMANTICS:
            raise ValueError(f"stamp semantics must be one of {sorted(STAMP_SEMANTICS)}")
        if self.uncertainty_s < 0:
            raise ValueError("stamp uncertainty cannot be negative")

    def comparable_with(self, other: "Stamp") -> bool:
        """Whether the two stamps are on the same clock, so a difference means something."""
        return self.domain == other.domain

    def delta_s(self, other: "Stamp") -> float:
        """``self - other`` in seconds, refusing unrelated clocks.

        Raises :class:`CalibrationFailure` with
        :data:`~leapcalib.contracts.failures.FAILURE_CLOCK_DOMAIN_MISMATCH` rather
        than returning the meaningless difference of two unrelated origins.
        """
        if not self.comparable_with(other):
            raise CalibrationFailure(
                FAILURE_CLOCK_DOMAIN_MISMATCH,
                f"cannot difference {self.domain} against {other.domain}",
            )
        return self.seconds - other.seconds

    def spread_s(self, other: "Stamp") -> float:
        """Worst-case separation of the two instants, including both uncertainties."""
        return abs(self.delta_s(other)) + self.uncertainty_s + other.uncertainty_s

    def to_dict(self) -> dict[str, Any]:
        return {
            "seconds": self.seconds,
            "domain": self.domain,
            "semantics": self.semantics,
            "uncertainty_s": self.uncertainty_s,
        }

    @classmethod
    def from_mapping(cls, data: Mapping[str, Any]) -> "Stamp":
        return cls(
            seconds=float(data["seconds"]),
            domain=str(data.get("domain") or CLOCK_NODE_MONOTONIC),
            semantics=str(data.get("semantics") or STAMP_RECEIPT),
            uncertainty_s=float(data.get("uncertainty_s") or 0.0),
        )


@dataclass(frozen=True)
class PixelDepthSample:
    """One pixel with its metric depth, optionally labelled with what it fell on.

    ``depth_m`` of 0.0 means "no measurement", as in ``RgbdFrame``. ``link_id``
    carries the link a depth-to-native-geometry residual believes this sample
    landed on; it is an assertion by whoever built the observation, and a solve
    is expected to re-check occlusion rather than trust it blindly.
    """

    u_px: float
    v_px: float
    depth_m: float
    link_id: str = ""
    weight: float = 1.0

    def __post_init__(self) -> None:
        for name in ("u_px", "v_px", "depth_m", "weight"):
            object.__setattr__(self, name, canonical_number(getattr(self, name)))
        if self.depth_m < 0:
            raise ValueError("depth cannot be negative; 0.0 means no measurement")
        if self.weight < 0:
            raise ValueError("a sample weight cannot be negative")

    @property
    def measured(self) -> bool:
        return self.depth_m > 0.0

    def to_dict(self) -> dict[str, Any]:
        return {
            "u_px": self.u_px,
            "v_px": self.v_px,
            "depth_m": self.depth_m,
            "link_id": self.link_id,
            "weight": self.weight,
        }

    @classmethod
    def from_mapping(cls, data: Mapping[str, Any]) -> "PixelDepthSample":
        return cls(
            u_px=float(data["u_px"]),
            v_px=float(data["v_px"]),
            depth_m=float(data["depth_m"]),
            link_id=str(data.get("link_id") or ""),
            weight=float(data.get("weight", 1.0)),
        )


@dataclass(frozen=True)
class RgbdObservation:
    """A bounded set of metric depth samples from one stream at one instant.

    Deliberately not an image. The first transport carries sampled keyframes and
    regions of interest, so an observation is the reduced thing a residual
    consumes; a full frame never has to cross a process boundary for P0 to be
    inspectable.
    """

    observation_id: str
    stream: StreamProfile
    stamp: Stamp
    provenance: str
    samples: tuple[PixelDepthSample, ...] = ()
    metadata: Mapping[str, Any] = field(default_factory=dict)

    def __post_init__(self) -> None:
        if not self.observation_id.strip():
            raise ValueError("an observation needs a nonempty id")
        if self.provenance not in PROVENANCES:
            raise ValueError(f"provenance must be one of {sorted(PROVENANCES)}")
        if self.provenance not in CALIBRATION_PROVENANCE:
            raise CalibrationFailure(
                FAILURE_PROVENANCE_REFUSED,
                f"{self.provenance} is not metric calibration evidence",
            )
        object.__setattr__(self, "samples", tuple(self.samples))
        if len(self.samples) > MAX_SAMPLES:
            raise ValueError(f"an observation carries at most {MAX_SAMPLES} samples")
        for sample in self.samples:
            if not self.stream.contains_pixel(sample.u_px, sample.v_px):
                raise ValueError(
                    f"sample ({sample.u_px}, {sample.v_px}) is outside "
                    f"{self.stream.width}x{self.stream.height}"
                )

    @property
    def measured_samples(self) -> tuple[PixelDepthSample, ...]:
        """Samples that carry a depth measurement inside the stream's valid range."""
        return tuple(
            s for s in self.samples if s.measured and self.stream.depth_in_range(s.depth_m)
        )

    @property
    def valid_ratio(self) -> float:
        """Share of samples usable as depth evidence; 0.0 for an empty observation."""
        return len(self.measured_samples) / len(self.samples) if self.samples else 0.0

    def to_dict(self) -> dict[str, Any]:
        return {
            "observation_id": self.observation_id,
            "kind": "rgbd",
            "stream": self.stream.to_dict(),
            "stamp": self.stamp.to_dict(),
            "provenance": self.provenance,
            "samples": [s.to_dict() for s in self.samples],
            "metadata": dict(self.metadata),
        }

    @classmethod
    def from_mapping(cls, data: Mapping[str, Any]) -> "RgbdObservation":
        return cls(
            observation_id=str(data["observation_id"]),
            stream=StreamProfile.from_mapping(data["stream"]),
            stamp=Stamp.from_mapping(data["stamp"]),
            provenance=str(data["provenance"]),
            samples=tuple(PixelDepthSample.from_mapping(s) for s in data.get("samples") or ()),
            metadata=dict(data.get("metadata") or {}),
        )

    @property
    def digest(self) -> str:
        return digest_of(self.to_dict())


@dataclass(frozen=True)
class JointObservation:
    """Raw joint feedback at one instant, in radians, with its settling evidence.

    ``q_raw_rad`` is firmware feedback -- the nominal command model's coordinates,
    never a corrected physical angle. ``still`` records that motion had actually
    settled when the sample was taken, which is what makes a receipt-stamped
    camera frame usable alongside it; a commanded arrival flag is not stillness,
    so ``max_speed_rad_s`` carries the measured bound.
    """

    observation_id: str
    model: ModelIdentity
    stamp: Stamp
    q_raw_rad: tuple[float, ...]
    still: bool = False
    max_speed_rad_s: float = 0.0
    metadata: Mapping[str, Any] = field(default_factory=dict)

    def __post_init__(self) -> None:
        if not self.observation_id.strip():
            raise ValueError("an observation needs a nonempty id")
        object.__setattr__(self, "q_raw_rad", tuple(canonical_number(q) for q in self.q_raw_rad))
        if len(self.q_raw_rad) != self.model.dof:
            raise ValueError(
                f"model {self.model.model_id} has {self.model.dof} joints, "
                f"got {len(self.q_raw_rad)} values"
            )
        if type(self.still) is not bool:
            raise ValueError("stillness must be an explicit boolean")
        object.__setattr__(self, "max_speed_rad_s", canonical_number(self.max_speed_rad_s))
        if self.max_speed_rad_s < 0:
            raise ValueError("a measured speed bound cannot be negative")

    def to_dict(self) -> dict[str, Any]:
        return {
            "observation_id": self.observation_id,
            "kind": "joints",
            "model": self.model.to_dict(),
            "stamp": self.stamp.to_dict(),
            "q_raw_rad": list(self.q_raw_rad),
            "still": self.still,
            "max_speed_rad_s": self.max_speed_rad_s,
            "metadata": dict(self.metadata),
        }

    @classmethod
    def from_mapping(cls, data: Mapping[str, Any]) -> "JointObservation":
        return cls(
            observation_id=str(data["observation_id"]),
            model=ModelIdentity(**dict(data["model"])),
            stamp=Stamp.from_mapping(data["stamp"]),
            q_raw_rad=tuple(float(q) for q in data["q_raw_rad"]),
            still=data.get("still", False),
            max_speed_rad_s=float(data.get("max_speed_rad_s") or 0.0),
            metadata=dict(data.get("metadata") or {}),
        )

    @property
    def digest(self) -> str:
        return digest_of(self.to_dict())


Observation = RgbdObservation | JointObservation
"""Either observation kind; both carry an id, a stamp and an identity."""


def pair_spread_s(camera: RgbdObservation, joints: JointObservation) -> float:
    """Worst-case separation between a camera and a joint observation.

    This is the number a delay budget consumes, and it raises on unrelated clocks
    instead of producing a small-looking value. The spread includes both
    uncertainties, so a receipt-stamped pair cannot look better than it is.
    """
    return camera.stamp.spread_s(joints.stamp)


def observation_dict(observation: Observation) -> dict[str, Any]:
    """Serialise either observation kind; the ``kind`` field is what reads it back."""
    return observation.to_dict()


def observation_from_mapping(data: Mapping[str, Any]) -> Observation:
    """Rebuild whichever observation kind *data* declares."""
    kind = str(data.get("kind") or "")
    if kind == "rgbd":
        return RgbdObservation.from_mapping(data)
    if kind == "joints":
        return JointObservation.from_mapping(data)
    raise ValueError(f"unknown observation kind {kind!r}")


@runtime_checkable
class ObservationSource(Protocol):
    """Where observations come from, with their identity and provenance attached.

    The seam that lets the same method run against a live node, a recording, or a
    synthetic study without the method knowing which. Implemented in P0 by
    ``leapcalib.validation.bundle.ReplaySource``; a live node-backed source
    arrives with the acquisition work it needs, since nothing offline can supply
    one honestly.

    A source hands over data. It never grants motion, and it cannot widen what
    its deployment already permits.
    """

    @property
    def topology_digest(self) -> str:
        """Identity of the hardware these observations were taken against."""
        ...

    def observations(self) -> Iterator[Observation]:
        """Iterate the available observations in recorded order."""
        ...


def total_valid_ratio(observations: Sequence[Observation]) -> float:
    """Share of depth samples usable across *observations*; 0.0 when there are none.

    Joint observations carry no depth samples and are skipped, so this measures
    depth evidence density rather than being diluted by them.
    """
    total = measured = 0
    for observation in observations:
        if isinstance(observation, RgbdObservation):
            total += len(observation.samples)
            measured += len(observation.measured_samples)
    return measured / total if total else 0.0


def worst_stamp_uncertainty_s(observations: Sequence[Observation]) -> float:
    """Largest stamp uncertainty present, which bounds any timing claim made from them."""
    return max((o.stamp.uncertainty_s for o in observations), default=0.0)


def settled_fraction(observations: Sequence[Observation]) -> float:
    """Share of joint observations taken with measured stillness; 0.0 when there are none.

    The settle-then-capture qualification depends on this being high, so it is
    reported rather than assumed.
    """
    joints = [o for o in observations if isinstance(o, JointObservation)]
    return sum(1 for o in joints if o.still) / len(joints) if joints else 0.0


def assert_finite(*values: float) -> None:
    """Guard for a boundary that has not yet gone through a canonicalising type."""
    if not all(math.isfinite(v) for v in values):
        raise ValueError("values must be finite")


